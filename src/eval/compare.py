"""One table across the evaluation versions (C2): python -m src.eval.compare  ->  docs/eval_versions.md

Every number is read from the saved results (data/processed/eval/<folder>/results_*.jsonl); nothing is typed by hand.
All versions use the same LLM (DeepSeek flash) and the same cases; only the full agent changed between versions.
"""
from __future__ import annotations

import json
from pathlib import Path

from .cases import load_cases
from .metrics import code_metrics, refusal_metrics, wilson

EVAL = Path("data/processed/eval")
VERSIONS = [
    ("v0", "deepseek", "full_graph", "first run: search only, no heading hints"),
    ("v1", "deepseek_hints", "full_graph", "+ the LLM proposes 4-digit headings; the exact Pakistan lines under them join the pool"),
    ("v2", "deepseek_v2", "full_graph", "+ refuses misdeclaration and non-import questions; 'one product' fix"),
    ("v3", "deepseek_v3", "full_graph", "+ 131 Classification Committee precedents (each case's own notice and its repeats removed)"),
    ("v3a", "deepseek_v3", "full_graph_assisted", "v3 with a simulated importer who answers the agent's classification questions from the description only"),
    ("v4", "deepseek_v4", "full_graph", "v3 + reasoning (thinking) switched on for the Classify step only"),
]
BASELINES = [("plain LLM", "deepseek_v4", "plain_llm"), ("LLM + search", "deepseek_v4", "llm_rag"), ("TariffAI (6-digit)", "deepseek_v4", "tariffai")]


def load(folder: str, system: str) -> list[dict]:
    p = EVAL / folder / f"results_{system}.jsonl"
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()] if p.exists() else []


def fmt(h: int, n: int) -> str:
    if not n:
        return "n/a"
    lo, hi = wilson(h, n)
    return f"{h}/{n} ({100 * h / n:.0f}%, {100 * lo:.0f}-{100 * hi:.0f})"


def cells(rows: list[dict], cases: dict, kind: str):
    r = [dict(expected=[x["expected"]] + cases[x["case_id"]].alt_codes, pred=x["pred"]["codes"]) for x in rows
         if x["kind"] == kind and x["case_id"] in cases and cases[x["case_id"]].behavior == "answer" and x["expected"]]
    return code_metrics(r)


def behaviour(rows: list[dict], cases: dict):
    syn = [dict(expected_behavior=cases[x["case_id"]].behavior, behavior=x["pred"]["behavior"], pred=x["pred"]["codes"],
                candidate_headings=cases[x["case_id"]].candidate_headings) for x in rows if x["kind"] == "synthetic" and x["case_id"] in cases]
    return refusal_metrics(syn)


def build() -> str:
    cases = {c.id: c for c in load_cases()}
    L = ["# Evaluation across versions (generated by `python -m src.eval.compare`; do not edit by hand)", "",
         "Same LLM (DeepSeek flash) and same cases for every row. Format: hits/n (percent, 95% Wilson interval). Real = 79 cases from public rulings "
         "(66 are disputes, so this is a stress test on contested goods). Synthetic = 60 cases written by Claude, labels unverified. The intervals are wide: "
         "differences of a few cases are noise.", ""]
    for kind, n8 in (("real", "70 with an 8-digit answer"), ("synthetic", "45 with an 8-digit answer")):
        L += [f"## {kind.capitalize()} cases ({n8})", "", "| Version | What changed | Heading (4-digit) top-1 | Exact 8-digit line top-1 | Right 8-digit line in top 3 |", "|---|---|---|---|---|"]
        for name, folder, system, what in VERSIONS:
            rows = load(folder, system)
            if rows:
                m = cells(rows, cases, kind)
                L.append(f"| {name} | {what} | {fmt(*m[(1, 4)])} | {fmt(*m[(1, 8)])} | {fmt(*m[(5, 8)])} |")
        for name, folder, system in BASELINES:
            rows = load(folder, system)
            if rows:
                m = cells(rows, cases, kind)
                top8 = ("not possible", "not possible") if system == "tariffai" else (fmt(*m[(1, 8)]), fmt(*m[(5, 8)]))
                L.append(f"| baseline | {name} | {fmt(*m[(1, 4)])} | {top8[0]} | {top8[1]} |")
        L.append("")
    L += ["## Asking and refusing (synthetic cases only: 9 should ask, 3 should refuse)", "", "| Version | Asked or said not sure when it should | Refused when it should |", "|---|---|---|"]
    for name, folder, system, _ in VERSIONS:
        rows = load(folder, system)
        if rows:
            m = behaviour(rows, cases)
            L.append(f"| {name} | {m['not_sure_or_clarify'][0]}/{m['not_sure_or_clarify'][1]} | {m['refuse'][0]}/{m['refuse'][1]} |")
    L += ["", "The 'full agent' rows count a paused run (the agent asked a question) by the candidates it had at that moment; nobody answers except in v3a."]
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    Path("docs/eval_versions.md").write_text(build(), encoding="utf-8")
    print("wrote docs/eval_versions.md")
