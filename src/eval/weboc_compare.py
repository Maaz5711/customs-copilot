"""Compare compute_duty with the official WeBOC duty calculator (independent check of the duty side).

    python -m src.eval.weboc_compare           ->  docs/weboc_comparison.md  and  data/processed/eval/weboc_comparison.csv

Input: data/ground_truth/weboc_calculator_2026-10-16.json (answers captured from the public calculator; see its _meta).
WeBOC facts that matter for reading the comparison (observed):
* it prints rates rounded to whole percent, amounts truncated to whole rupees;
* it shows income tax at the non-filer rate for every code (12%) and does not classify goods into Twelfth Schedule parts;
* it shows no 3% value-addition tax and no further tax; it has no inputs for engine size, registration or filer status.
So we compare customs duty (CD), regulatory duty (RD), additional customs duty (ACD), sales tax (ST) and federal excise duty (FED) AMOUNTS (tolerance 1 rupee),
and for income tax only the rate (ours for a commercial importer who is not a filer) because the tax base differs by the 3% tax.
"""
from __future__ import annotations

import csv
import json
from decimal import Decimal
from pathlib import Path

from src.tools import compute_duty

DATA = Path("data/ground_truth/weboc_calculator_2026-10-16.json")
DATE = "2026-10-16"
VALUE = "2829247"
NAMES = {"Customs Duty": "CD", "Sales Tax": "ST", "Regulatory Duty": "RD", "Income Tax": "IT", "Additional Custom Duty": "ACD",
         "Federal Excise Duty": "FED", "Special Excise Duty": "SED"}
IMPORTER = {"registration_status": "registered", "commercial_importer": True, "active_taxpayer": False, "manufacturer_in_house_use": False}
GOODS = {"plant_machinery_for_manufacturing": False}


def parse_cells(raw: str) -> dict:
    """'2008.5000|Customs Duty|15%|424387|7|2008.5000|Sales Tax|25%|926578|9|...' -> {'CD': ('15', 424387), ...}"""
    cells = raw.split("|")
    out = {}
    for i, c in enumerate(cells):
        if c in NAMES:
            rate, amt = cells[i + 1], cells[i + 2]
            out[NAMES[c]] = (rate.rstrip("%"), int(amt))
    return out


def ours(code: str) -> dict:
    r = compute_duty(code, VALUE, DATE, importer=IMPORTER, goods=GOODS)
    res = {"status": r["status"], "lines": {}, "missing": [m["field"] for m in r.get("missing_inputs", [])] if r["status"] == "needs_input" else [],
           "cannot": r.get("cannot_compute") if r["status"] == "cannot_compute" else None}
    for ln in r.get("lines", []) + r.get("optional_lines_not_in_total", []):
        res["lines"].setdefault(ln["tax"], (ln["rate"].get("pct") if isinstance(ln.get("rate"), dict) else None, Decimal(ln["amount_pkr"])))
    return res


def compare() -> list[dict]:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    rows = []
    for code, (uom, desc, raw) in ((k, v) for k, v in data.items() if not k.startswith("_")):
        w = parse_cells(raw)
        o = ours(code)
        row = {"code": code, "desc": desc.strip(), "our_status": o["status"], "needs": ";".join(o["missing"]), "diffs": []}
        for tax in ("CD", "RD", "ACD", "ST", "FED"):
            wa = w.get(tax, (None, 0))[1]
            oa = o["lines"].get(tax, (None, Decimal(0)))[1] if o["status"] in ("computed",) else None
            row[f"weboc_{tax}"] = wa
            row[f"ours_{tax}"] = None if oa is None else int(oa)
            if oa is not None and abs(Decimal(wa) - oa) > 1:
                row["diffs"].append(f"{tax}: WeBOC {wa} vs ours {oa}")
        wit = w.get("IT", (None, 0))[0]
        oit = o["lines"].get("IT", (None, None))[0] if o["status"] == "computed" else None
        row["weboc_IT_rate"], row["ours_IT_rate"] = wit, oit
        if oit is not None and wit is not None and Decimal(oit) != Decimal(wit):
            row["diffs"].append(f"IT rate: WeBOC {wit}% vs ours {oit}%")
        rows.append(row)
    return rows


def write(rows: list[dict]) -> None:
    out_csv = Path("data/processed/eval/weboc_comparison.csv")
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    cols = ["code", "desc", "our_status", "needs", "weboc_CD", "ours_CD", "weboc_RD", "ours_RD", "weboc_ACD", "ours_ACD", "weboc_ST", "ours_ST", "weboc_FED", "ours_FED", "weboc_IT_rate", "ours_IT_rate", "diffs"]
    with open(out_csv, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({**r, "diffs": " | ".join(r["diffs"])})
    comp = [r for r in rows if r["our_status"] == "computed"]
    ok = [r for r in comp if not r["diffs"]]
    L = ["# Our duty tool against the official WeBOC calculator (generated by `python -m src.eval.weboc_compare`)", "",
         f"{len(rows)} tariff codes of FY2026-27, import value PKR {VALUE} on {DATE}. WeBOC answers saved in `{DATA}` (captured from the public calculator; not an owner check).",
         "We compare customs duty, regulatory duty, additional customs duty, sales tax and federal excise duty amounts to the rupee (WeBOC truncates), and the income-tax RATE "
         "(ours for a commercial importer who is not a filer). WeBOC prints no 3% value-addition tax and no further tax, so those are not compared.", "",
         f"* Codes our tool could compute on these inputs: {len(comp)} of {len(rows)}. The rest need more facts from the importer (listed below), so they are not compared.",
         f"* Of the {len(comp)} computed, **{len(ok)} match WeBOC on every compared line**; {len(comp) - len(ok)} differ.", ""]
    if len(comp) != len(ok):
        L += ["## Differences", "", "| Code | Description | Difference(s) |", "|---|---|---|"]
        for r in comp:
            if r["diffs"]:
                L.append(f"| {r['code']} | {r['desc'][:40]} | {'; '.join(r['diffs'])} |")
        L.append("")
    nc = [r for r in rows if r["our_status"] != "computed"]
    if nc:
        L += ["## Not compared (our tool asks the importer, or says it cannot compute)", "", "| Code | Description | Our tool | Needs |", "|---|---|---|---|"]
        for r in nc:
            L.append(f"| {r['code']} | {r['desc'][:40]} | {r['our_status']} | {r['needs']} |")
        L.append("")
    Path("docs/weboc_comparison.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(rows)} codes; computed {len(comp)}; match {len(ok)}; differ {len(comp) - len(ok)}; not compared {len(nc)}")


if __name__ == "__main__":
    write(compare())
