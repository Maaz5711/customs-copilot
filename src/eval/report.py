"""Build docs/eval_report.md from the saved results (C2). Numbers exist only for cases that were actually run.

Rules written into every report: sample sizes next to every number, 95% Wilson intervals, real and synthetic reported separately,
the systems compared on the SAME cases (the intersection), and the limits of the test set stated in the text.
"""
from __future__ import annotations

import csv
from pathlib import Path

from .citations import score_citations
from .metrics import code_metrics, duty_match, refusal_metrics, wilson
from .systems import SYSTEMS

ALL = SYSTEMS + ("tariffai",)      # tariffai = Danial's baseline, run from its own folder (results_tariffai.jsonl), 6-digit HS only

OUT = Path("data/processed/eval")
REPORT = Path("docs/eval_report.md")
DUTY_CASES = Path("data/ground_truth/duty_cases.csv")


def _load(out: Path) -> dict[str, dict[str, dict]]:
    from .run import load_results

    return {s: load_results(s, out) for s in ALL}


def _fmt(hits: int, n: int) -> str:
    if n == 0:
        return "n/a (n=0)"
    lo, hi = wilson(hits, n)
    return f"{100 * hits / n:.0f}% ({hits}/{n}; 95% CI {100 * lo:.0f}-{100 * hi:.0f}%)"


def _expected(rec: dict, alts: dict) -> list[str]:
    return [rec["expected"]] + alts.get(rec["case_id"], [])


def build(out: Path = OUT, llm_name: str = "") -> str:
    from .cases import load_cases

    res = _load(out)
    cases = {c.id: c for c in load_cases()}
    alts = {c.id: c.alt_codes for c in cases.values()}
    ran = [s for s in ALL if res[s]]
    L = ["# Evaluation report (generated by `python -m src.eval.run --report`; do not edit by hand)", ""]
    if llm_name:
        L += [f"LLM used for every system in this report: **{llm_name}** (results in `{out}`). Numbers from different LLMs are never mixed.", ""]
    L += ["**Read this first.** The test set is small, part of it is written by Claude (synthetic, not checked by a customs expert), and the real "
          "part comes from public Pakistani rulings (mostly one Karachi classification committee) and leans to machinery, electronics and "
          "chemicals. Intervals are wide. Real and synthetic results are never averaged. Systems are compared on the same cases only.", ""]
    if not ran:
        return "\n".join(L + ["No results yet. Run `python -m src.eval.run`."]) + "\n"
    L += ["## Coverage (cases run so far)", "", "| System | real | synthetic | errors/crashes |", "|---|---|---|---|"]
    for s in ALL:
        r = res[s]
        L.append(f"| {s} | {sum(1 for x in r.values() if x['kind'] == 'real')} | {sum(1 for x in r.values() if x['kind'] == 'synthetic')} | "
                 f"{sum(1 for x in r.values() if x['pred']['behavior'] == 'error')} |")
    common = (set.intersection(*[set(res[s]) for s in ran]) if ran else set()) & set(cases)
    L += ["", f"Systems with results: {', '.join(ran)}. Compared on the **{len(common)} cases that every one of them has run** "
              f"(real {sum(1 for c in common if cases[c].kind == 'real')}, synthetic {sum(1 for c in common if cases[c].kind == 'synthetic')}).", ""]
    for kind in ("real", "synthetic"):
        ids = [c for c in common if cases[c].kind == kind and cases[c].behavior == "answer" and cases[c].expected]
        L += [f"## Code accuracy: {kind} cases with an expected code (n={len(ids)})", ""]
        if kind == "synthetic":
            L += ["Synthetic: expected codes were written by Claude and are unverified; a mismatch may be the label's mistake.", ""]
        L += ["A prediction counts at level L when one of the first k codes shares the first L digits with the expected code "
              "(or an accepted alternative). Cases whose expected code is shorter than L are left out of that cell. The full graph shows at most "
              "3 candidates, so its top-5 equals its top-3. A refusal or a 'not sure' counts as a miss.", "",
              "| System | top-1 @4 | top-1 @6 | top-1 @8 | top-5 @4 | top-5 @6 | top-5 @8 |", "|---|---|---|---|---|---|---|"]
        for s in ran:
            rows = [dict(expected=_expected(res[s][c], alts), pred=res[s][c]["pred"]["codes"]) for c in ids]
            m = code_metrics(rows)
            L.append(f"| {s} | " + " | ".join("n/a (6-digit system)" if (s == "tariffai" and lv == 8) else _fmt(*m[(k, lv)]) for k in (1, 5) for lv in (4, 6, 8)) + " |")
        L.append("")
    syn_ids = [c for c in common if cases[c].kind == "synthetic"]
    L += [f"## Refusal and asking quality: synthetic cases (n={len(syn_ids)} run by every system)", "",
          "Expected behaviour is one of: answer, not_sure_or_clarify (9 cases in the full set), refuse (3). Counts are small; read them as examples.", "",
          "| System | asked/not sure when it should | refused when it should | answered when it should | not-sure showed the right heading |", "|---|---|---|---|---|"]
    for s in ran:
        rows = [dict(expected_behavior=cases[c].behavior, behavior=res[s][c]["pred"]["behavior"], pred=res[s][c]["pred"]["codes"],
                     candidate_headings=cases[c].candidate_headings) for c in syn_ids]
        m = refusal_metrics(rows)
        L.append(f"| {s} | {_fmt(*m['not_sure_or_clarify'])} | {_fmt(*m['refuse'])} | {_fmt(*m['answer'])} | {_fmt(*m['not_sure_shows_right_heading'])} |")
    L.append("")
    fg = res["full_graph"]
    L += ["## Citation correctness (full graph only; other systems give no citations)", ""]
    if fg:
        tot = ok = n_ans = 0
        bad = []
        for c, r in fg.items():
            if c not in cases:
                continue
            cites = r["pred"].get("citations") or []
            if not cites:
                continue
            n_ans += 1
            sc = score_citations(cites, r["as_of_date"])
            tot += sc["checked"]
            ok += sc["correct"]
            bad += [(c, w) for w in sc["wrong"]]
        L += [f"Answers with citations: {n_ans}. Citations checked: {_fmt(ok, tot)} point at a real fact row (tariff line on the date with the same file and "
              "page, or a store row for that file and page). This checks the pointer, not the legal claim.", ""]
        for c, w in bad[:10]:
            L.append(f"- {c}: {w.get('kind')} {w.get('code') or w.get('instrument') or ''} {w.get('source_file')} p{w.get('page')}: {w['reason']}")
        L.append("")
    else:
        L += ["No full-graph results yet.", ""]
    L += ["## Duty match (hand-computed bills)", ""]
    n_duty = 0
    if DUTY_CASES.exists() and fg:
        rows = list(csv.DictReader(open(DUTY_CASES, encoding="utf-8")))
        done = [r for r in rows if r["id"] in fg]
        hits = sum(duty_match(fg[r["id"]]["pred"].get("bill_totals"), r["expected_total_payable_pkr"]) for r in done)
        n_duty = len(done)
        L.append(f"Full graph: {_fmt(hits, n_duty)} bills equal the hand-computed total to the paisa.")
    if not n_duty:
        L.append("n=0: there are no hand-computed bills yet (`data/ground_truth/duty_cases.csv` is empty). No duty-match number is claimed.")
    L += ["", "## Baseline: Danial's TariffAI", ""]
    if res["tariffai"]:
        L += ["TariffAI (MIT per its README; reference only, no code copied) ran from its own folder on the same cases. Differences from the original: "
              "Qdrant in local mode instead of Docker, and its single LLM call goes to the same DeepSeek flash model instead of Gemini (same prompt, same parsing). "
              "It classifies into the international 6-digit HS list, not Pakistan's 8-digit tariff, so it is scored at 4 and 6 digits only. "
              "Its 'ambiguous' flag (confidence below 0.7) is counted as asking/not sure.", ""]
    else:
        L += ["Not run yet.", ""]
    return "\n".join(L) + "\n"


def write_report(out: Path = OUT, path: Path = REPORT, llm_name: str = "") -> Path:
    path.write_text(build(out, llm_name), encoding="utf-8")
    print("wrote", path)
    return path
